    private void jButton2ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton2ActionPerformed
        
    try {
        // Ask for Record ID
        String recordIdInput = javax.swing.JOptionPane.showInputDialog(
                this,
                "Enter Record ID to update:"
        );

        // Cancel or empty input
        if (recordIdInput == null || recordIdInput.trim().isEmpty()) {
            return;
        }

        int recordId = Integer.parseInt(recordIdInput.trim());

        // Get values from form
        int patientId = Integer.parseInt(jTextField1.getText().trim());
        int doctorId = Integer.parseInt(jTextField2.getText().trim());

        String diagnosis = jTextField3.getText().trim();
        String treatment = jTextField4.getText().trim();
        String notes = jTextArea1.getText().trim();
        String recordDate = jTextField5.getText().trim();

        // Check date
        if (recordDate.isEmpty()) {
            javax.swing.JOptionPane.showMessageDialog(
                    this,
                    "Please enter record date."
            );
            return;
        }

        java.sql.Date date = java.sql.Date.valueOf(recordDate);

        // SQL UPDATE query
        String sql = "UPDATE medical_records SET "
                + "patient_id = ?, "
                + "doctor_id = ?, "
                + "diagnosis = ?, "
                + "treatment = ?, "
                + "notes = ?, "
                + "record_date = ? "
                + "WHERE record_id = ?";

        java.sql.Connection connection = DBConnection.getConnection();

        java.sql.PreparedStatement statement =
                connection.prepareStatement(sql);

        statement.setInt(1, patientId);
        statement.setInt(2, doctorId);
        statement.setString(3, diagnosis);
        statement.setString(4, treatment);
        statement.setString(5, notes);
        statement.setDate(6, date);
        statement.setInt(7, recordId);

        int rowsUpdated = statement.executeUpdate();

        statement.close();
        connection.close();

        if (rowsUpdated > 0) {
            javax.swing.JOptionPane.showMessageDialog(
                    this,
                    "Medical record updated successfully!"
            );
        } else {
            javax.swing.JOptionPane.showMessageDialog(
                    this,
                    "No medical record found with Record ID: " + recordId
            );
        }

    } catch (NumberFormatException e) {

        javax.swing.JOptionPane.showMessageDialog(
                this,
                "Patient ID, Doctor ID and Record ID must be valid numbers."
        );

    } catch (IllegalArgumentException e) {

        javax.swing.JOptionPane.showMessageDialog(
                this,
                "Please enter the date in YYYY-MM-DD format."
        );

    } catch (java.sql.SQLException e) {

        javax.swing.JOptionPane.showMessageDialog(
                this,
                "Database error: " + e.getMessage()
        );
    }

    }//GEN-LAST:event_jButton2ActionPerformed

    private void jButton3ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton3ActionPerformed
        
    try {
        // Ask for Record ID
        String recordIdInput = javax.swing.JOptionPane.showInputDialog(
                this,
                "Enter Record ID to delete:"
        );

        // Cancel or empty input
        if (recordIdInput == null || recordIdInput.trim().isEmpty()) {
            return;
        }

        int recordId = Integer.parseInt(recordIdInput.trim());

        // SQL DELETE query
        String sql = "DELETE FROM medical_records WHERE record_id = ?";

        java.sql.Connection connection = DBConnection.getConnection();

        java.sql.PreparedStatement statement =
                connection.prepareStatement(sql);

        statement.setInt(1, recordId);

        int rowsDeleted = statement.executeUpdate();

        statement.close();
        connection.close();

        if (rowsDeleted > 0) {
            javax.swing.JOptionPane.showMessageDialog(
                    this,
                    "Medical record deleted successfully!"
            );
        } else {
            javax.swing.JOptionPane.showMessageDialog(
                    this,
                    "No medical record found with Record ID: " + recordId
            );
        }

    } catch (NumberFormatException e) {

        javax.swing.JOptionPane.showMessageDialog(
                this,
                "Record ID must be a valid number."
        );

    } catch (java.sql.SQLException e) {

        javax.swing.JOptionPane.showMessageDialog(
                this,
                "Database error: " + e.getMessage()
        );
    }

    }//GEN-LAST:event_jButton3ActionPerformed

