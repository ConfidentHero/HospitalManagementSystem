    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed

    try {
        int patientId = Integer.parseInt(jTextField1.getText().trim());
        int doctorId = Integer.parseInt(jTextField2.getText().trim());

        String diagnosis = jTextField3.getText().trim();
        String treatment = jTextField4.getText().trim();
        String notes = jTextArea1.getText().trim();
        String recordDate = jTextField5.getText().trim();

        if (recordDate.isEmpty()) {
            javax.swing.JOptionPane.showMessageDialog(
                    this,
                    "Please enter record date."
            );
            return;
        }

        java.sql.Date date = java.sql.Date.valueOf(recordDate);

        String sql = "INSERT INTO medical_records "
                + "(patient_id, doctor_id, diagnosis, treatment, notes, record_date) "
                + "VALUES (?, ?, ?, ?, ?, ?)";

        java.sql.Connection connection = DBConnection.getConnection();
        java.sql.PreparedStatement statement =
                connection.prepareStatement(sql);

        statement.setInt(1, patientId);
        statement.setInt(2, doctorId);
        statement.setString(3, diagnosis);
        statement.setString(4, treatment);
        statement.setString(5, notes);
        statement.setDate(6, date);

        statement.executeUpdate();

        statement.close();
        connection.close();

        javax.swing.JOptionPane.showMessageDialog(
                this,
                "Medical record added successfully!"
        );

    } catch (NumberFormatException e) {

        javax.swing.JOptionPane.showMessageDialog(
                this,
                "Patient ID and Doctor ID must be valid numbers."
        );

    } catch (IllegalArgumentException e) {

        javax.swing.JOptionPane.showMessageDialog(
                this,
                "Please enter the date in YYYY-MM-DD format."
        );

    } catch (java.sql.SQLException e) {

        javax.swing.JOptionPane.showMessageDialog(
                this,
                "Database error: " + e.getMessage()
        );
    }

    }//GEN-LAST:event_jButton1ActionPerformed

